import json
import requests


OLLAMA_URL = "http://127.0.0.1:11434/api/chat"
MODEL = "qwen3:4b-instruct"


COMMAND_SCHEMA = {
    "type": "object",
    "properties": {
        "action": {
            "type": "string",
            "enum": [
                "open_app",
                "open_website",
                "open_folder",
                "search_web",
                "youtube",
                "whatsapp_message",
                "screen_on",
                "screen_off",
                "click",
                "double_click",
                "right_click",
                "press_key",
                "read_pdf",
                "build_website",
                "standby",
                "stop",
                "chat",
            ],
        },
        "target": {
            "type": "string",
        },
        "message": {
            "type": "string",
        },
        "response": {
            "type": "string",
        },
    },
    "required": [
        "action",
        "target",
        "message",
        "response",
    ],
    "additionalProperties": False,
}


SYSTEM_PROMPT = """
You are the command-understanding layer of a Windows voice assistant named JARVIS.

Your job is NOT to answer the user.

Your job is to reconstruct the user's intended command from an imperfect
speech-to-text transcript.

The transcript may contain:
- misheard words
- phonetic mistakes
- wrong plurals
- missing words
- duplicated words
- incorrect punctuation
- slightly incorrect names
- speech-recognition errors
- incomplete grammar

Understand the ENTIRE sentence and its context.

Do NOT perform literal word replacement.

Example:

Transcript:
"send message in whatsapp to babies say this message was generated by AI"

Intended meaning:
Send a WhatsApp message to the contact "baby"
with message:
"this message was generated by AI"

Return:
action = whatsapp_message
target = baby
message = this message was generated by AI

Important:
- Never invent an action the user did not request.
- Never turn an action command into chat.
- For WhatsApp, separate CONTACT from MESSAGE correctly.
- "say", "saying", "that says" usually marks the beginning of the message.
- Preserve the user's intended message.
- If the transcript is already clear, return it unchanged semantically.
- Do not explain anything.
- Return ONLY JSON matching the supplied schema.
"""


def repair_command(text):
    """
    Convert imperfect STT text into a structured JARVIS command.
    Returns a normal JARVIS result dictionary.
    """

    if not text or not text.strip():
        return None

    payload = {
        "model": MODEL,
        "stream": False,
        "format": COMMAND_SCHEMA,
        "options": {
            "temperature": 0,
        },
        "messages": [
            {
                "role": "system",
                "content": SYSTEM_PROMPT,
            },
            {
                "role": "user",
                "content": text.strip(),
            },
        ],
    }

    try:

        response = requests.post(
            OLLAMA_URL,
            json=payload,
            timeout=(1.0, 4.0),
        )

        response.raise_for_status()

        data = response.json()

        content = (
            data
            .get("message", {})
            .get("content", "")
            .strip()
        )

        if not content:
            return None

        result = json.loads(content)

        return {
            "action": result.get("action", "chat"),
            "target": result.get("target", ""),
            "message": result.get("message", ""),
            "response": result.get("response", ""),
        }

    except Exception as error:

        print(
            f"⚠️ Command repair unavailable: {error}",
            flush=True,
        )

        return None